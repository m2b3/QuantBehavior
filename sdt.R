# Small helpers used throughout. Sorting inside auc_trapezoid makes it work
# whether an ROC was generated by increasing or decreasing thresholds.
auc_trapezoid <- function(x, y) {
  keep <- is.finite(x) & is.finite(y)
  x <- x[keep]
  y <- y[keep]
  ordering <- order(x)
  x <- x[ordering]
  y <- y[ordering]
  sum(diff(x) * (head(y, -1) + tail(y, -1)) / 2)
}

find_curve_crossing <- function(grid, difference, target = mean(range(grid))) {
  crossing_indices <- which(diff(sign(difference)) != 0)
  if (length(crossing_indices) == 0) {
    stop("No curve crossing was found on the supplied grid.")
  }
  crossings <- vapply(crossing_indices, function(index) {
    x1 <- grid[index]
    x2 <- grid[index + 1]
    y1 <- difference[index]
    y2 <- difference[index + 1]
    x1 - y1 * (x2 - x1) / (y2 - y1)
  }, numeric(1))
  crossings[which.min(abs(crossings - target))]
}

simulate_yes_count <- function(mean_response, n_trials, criterion, lapse) {
  internal_response <- rnorm(n_trials, mean_response, 1)
  respond_yes <- internal_response > criterion
  lapse_trials <- runif(n_trials) < lapse
  respond_yes[lapse_trials] <- runif(sum(lapse_trials)) < 0.5
  sum(respond_yes)
}

# -----------------------------------------------------------------------------
# 1. The ideal equal-variance model
# -----------------------------------------------------------------------------
# Imagine equally common signal and noise trials. Each trial creates a noisy,
# one-dimensional internal response. Signal responses tend to be larger, but
# the distributions overlap. Examples include baggage screening, radiology,
# hearing one's name, or diagnosing a sample from a noisy test.
#
# Our deliberately idealized starting assumptions are Gaussian signal and
# noise distributions with equal variance, independent stationary trials, one
# fixed decision criterion, and no stimulus-independent guesses or lapses.
#
# Three tasks that are easy to confuse
# Task                         Trial and response                 Direct summary
# Yes/no detection             Signal present/absent; say yes/no Hits, false alarms,
#                                                                d' and criterion
# Single-interval 2AFC         Category A or B; say A or B       A two-by-two table
# (identification)                                               after naming one
#                                                                category "positive"
# 2I-2AFC detection            Signal in interval 1 or 2;        Proportion correct
#                              choose its interval                and d'
#
# "2AFC" is sometimes used as shorthand for the two-interval task. Saying
# 1I-2AFC or 2I-2AFC removes that ambiguity. Sensitivity, specificity, recall,
# precision, and PPV apply naturally to yes/no detection and single-interval
# classification. In ordinary 2I-2AFC, a signal occurs somewhere on every
# trial, so catch trials or a separate yes/no task are needed to estimate
# detection specificity and predictive value.

