# -----------------------------------------------------------------------------
# Appendix A6. A non-Gaussian example
# -----------------------------------------------------------------------------
# Figure 8 replaces Figure 1's symmetric bell curves with skewed evidence
# distributions. The skew-normal shape parameter a controls the direction and
# degree of leaning. The density is 2*phi(z)*Phi(a*z)/scale. These small local
# functions avoid requiring the optional sn package.

skew_normal_pdf <- function(value, shape, location, scale) {
  z <- (value - location) / scale
  2 * dnorm(z) * pnorm(shape * z) / scale
}

skew_normal_cdf <- function(value, shape, location, scale) {
  vapply(
    value,
    function(upper) integrate(
      skew_normal_pdf, -Inf, upper,
      shape = shape, location = location, scale = scale,
      rel.tol = 1e-8
    )$value,
    numeric(1)
  )
}

rskew_normal <- function(n, shape, location, scale) {
  delta <- shape / sqrt(1 + shape^2)
  location + scale * (
    delta * abs(rnorm(n)) + sqrt(1 - delta^2) * rnorm(n)
  )
}

x_skew <- seq(0, 100, length.out = 1000)
shape_noise <- 2
loc_noise_skew <- 35
scale_noise_skew <- 10
shape_signal <- -2
loc_signal_skew <- 65
scale_signal_skew <- 10
pdf_noise_skew <- skew_normal_pdf(
  x_skew, shape_noise, loc_noise_skew, scale_noise_skew
)
pdf_signal_skew <- skew_normal_pdf(
  x_skew, shape_signal, loc_signal_skew, scale_signal_skew
)

plot(
  x_skew, pdf_noise_skew, type = "l", col = "red", lwd = 2,
  xlab = "Internal response", ylab = "Density",
  main = "Figure 8. A non-Gaussian pair of evidence distributions"
)
lines(x_skew, pdf_signal_skew, col = "blue", lwd = 2)
legend(
  "topright",
  c(
    sprintf("Noise: a=%g, loc=%g, scale=%g", shape_noise, loc_noise_skew, scale_noise_skew),
    sprintf("Signal: a=%g, loc=%g, scale=%g", shape_signal, loc_signal_skew, scale_signal_skew)
  ),
  col = c("red", "blue"), lty = 1, lwd = 2, bty = "n"
)
grid()

set.seed(603)
n_skew_samples <- 10000
simulated_noise_skew <- rskew_normal(
  n_skew_samples, shape_noise, loc_noise_skew, scale_noise_skew
)
simulated_signal_skew <- rskew_normal(
  n_skew_samples, shape_signal, loc_signal_skew, scale_signal_skew
)
p_correct_skew <- mean(simulated_signal_skew > simulated_noise_skew)

thresholds_skew <- seq(min(x_skew), max(x_skew), length.out = 100)
tpr_skew <- 1 - skew_normal_cdf(
  thresholds_skew, shape_signal, loc_signal_skew, scale_signal_skew
)
fpr_skew <- 1 - skew_normal_cdf(
  thresholds_skew, shape_noise, loc_noise_skew, scale_noise_skew
)
auc_skew <- auc_trapezoid(c(1, fpr_skew, 0), c(1, tpr_skew, 0))

cat(sprintf("Skew-normal simulated 2AFC probability correct: %.4f\n", p_correct_skew))
cat(sprintf("Skew-normal ROC AUC: %.4f\n", auc_skew))
stopifnot(
  auc_skew > 0 && auc_skew < 1,
  p_correct_skew > 0 && p_correct_skew < 1,
  abs(p_correct_skew - auc_skew) < 0.02
)

