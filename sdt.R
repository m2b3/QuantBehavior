  x_skew, shape_noise, loc_noise_skew, scale_noise_skew
)
pdf_signal_skew <- skew_normal_pdf(
  x_skew, shape_signal, loc_signal_skew, scale_signal_skew
)

plot(
  x_skew, pdf_noise_skew, type = "l", col = "red", lwd = 2,
  xlab = "Internal response", ylab = "Density",
