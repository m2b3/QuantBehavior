# Balanced yes/no accuracy at the optimal criterion is Phi(d'/2).
stopifnot(
  abs(p_correct_2afc - auc_analytic) < 1e-12,
  abs(p_correct_2afc - roc_auc) < 5e-4
)

# -----------------------------------------------------------------------------
# Appendix A4. Unequal priors and error costs
# -----------------------------------------------------------------------------
# Choose signal when the likelihood ratio exceeds
#   beta_optimal = P(noise)/P(signal) *
#                  (C_FA-C_CR)/(C_M-C_H).
# With equal error costs and P(noise)=3/4, P(signal)=1/4, beta_optimal=3.
# The accuracy-maximizing threshold is where prior-weighted densities cross.

prior_noise <- 3 / 4
prior_signal <- 1 / 4
weighted_noise <- prior_noise * pdf_noise
weighted_signal <- prior_signal * pdf_signal
weighted_intersection <- find_curve_crossing(
  x, weighted_signal - weighted_noise, (loc_noise + loc_signal) / 2
)
p_correct_unequal <-
  prior_signal * tpr_theoretical + prior_noise * (1 - fpr_theoretical)
analytic_weighted_intersection <-
  (loc_noise + loc_signal) / 2 +
  sd_noise^2 * log(prior_noise / prior_signal) / (loc_signal - loc_noise)
stopifnot(
  abs(weighted_intersection - analytic_weighted_intersection) < 2 * diff(x)[1],
  abs(thresholds[which.max(p_correct_unequal)] - weighted_intersection) <
    2 * diff(thresholds)[1]
)

old_par <- par(mfrow = c(1, 2))
plot(
  x, weighted_noise, type = "l", col = "red", lwd = 2,
  xlab = "Internal response", ylab = "Prior-weighted density",
  main = "Unequal priors"
)
lines(x, weighted_signal, col = "blue", lwd = 2)
points(
  weighted_intersection,
  prior_signal * dnorm(weighted_intersection, loc_signal, sd_signal),
  pch = 19
)
legend(
  "topright", c("P(noise) f_noise", "P(signal) f_signal"),
