# -----------------------------------------------------------------------------
# 4. Fit a psychometric function
# -----------------------------------------------------------------------------
# R has several possible psychometric-fitting routes. stats::glm is excellent
# for ordinary logit/probit binomial models without fitted lapses. The psyphy
# package (sometimes described informally as "R psychophysics") supplies SDT
# utilities, psychophysical GLM links, and psyfun.2asym; quickpsy adds a convenient
# multi-group/bootstrap workflow; brms can express richer Bayesian models. To
# keep this file immediately runnable, the code below directly maximizes the
# grouped-binomial likelihood with base stats::optim. This also lets us impose
# the same lower/upper-asymptote constraint used in the Python and MATLAB files.
#
# Curve choices:
#   norm     additive Gaussian decision noise: Phi(beta * (x - alpha))
#            In plain language, response chance is accumulated bell-curve area;
#            alpha moves the S-curve and beta controls how quickly it rises.
#   logistic logistic decision noise: plogis(beta * (x - alpha))
#            In plain language, every stimulus step adds a fixed amount to the
#            response log-odds. It resembles a Gaussian with heavier tails.
#   weibull  positive intensities: 1 - exp(-(x / alpha)^beta)
#            In plain language, the chance that every possible detection event
#            fails shrinks with intensity; alpha sets scale and beta sets shape.
#
# The response probability is q + (1 - 2q) * core(x), where the lower and
# upper error asymptotes are constrained to the same q. Under random lapses,
# the corresponding total lapse probability is 2q.

sigmoid_name <- "norm"  # Change to "logistic" or "weibull".

predict_psychometric <- function(theta, stimulus, sigmoid) {
  # q is constrained to (0, 0.1), slope/scale parameters stay positive.
  q <- 0.1 * plogis(theta[3])
  if (sigmoid == "weibull") {
    alpha <- exp(theta[1])
    beta <- exp(theta[2])
    core <- 1 - exp(-(pmax(stimulus, 0) / alpha)^beta)
  } else {
    alpha <- theta[1]
    beta <- exp(theta[2])
    linear_predictor <- beta * (stimulus - alpha)
    core <- if (sigmoid == "norm") pnorm(linear_predictor) else
      plogis(linear_predictor)
  }
  q + (1 - 2 * q) * core
}

psychometric_nll <- function(theta, data, sigmoid) {
  probabilities <- predict_psychometric(theta, data$contrast, sigmoid)
  probabilities <- pmin(pmax(probabilities, 1e-12), 1 - 1e-12)
  -sum(dbinom(data$yes, data$trials, probabilities, log = TRUE))
}

if (sigmoid_name == "weibull") {
  theta_start <- c(log(median(contrast_levels)), log(2), qlogis(0.1))
} else {
  theta_start <- c(median(contrast_levels), log(0.25), qlogis(0.1))
}

psychometric_fit <- optim(
  theta_start,
  psychometric_nll,
  data = psychometric_data,
  sigmoid = sigmoid_name,
  method = "Nelder-Mead",
  control = list(maxit = 10000, reltol = 1e-10),
  hessian = TRUE
)

fit_theta <- psychometric_fit$par
fit_q <- 0.1 * plogis(fit_theta[3])
if (sigmoid_name == "weibull") {
  fit_alpha <- exp(fit_theta[1])
  fit_beta <- exp(fit_theta[2])
} else {
  fit_alpha <- fit_theta[1]
  fit_beta <- exp(fit_theta[2])
}

fit_grid <- seq(0, max(contrast_levels), length.out = 400)
fit_probability <- predict_psychometric(fit_theta, fit_grid, sigmoid_name)
plot(
  fit_grid, fit_probability, type = "l", lwd = 2,
  xlab = "Contrast (%)", ylab = "Proportion of signal responses",
  ylim = c(0, 1), main = sprintf("Figure 4. Psychometric fit (%s link)", sigmoid_name)
)
points(contrast_levels, yes_counts / n_per_level, pch = 19, col = "blue")
