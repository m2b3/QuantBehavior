cat(sprintf(
  paste0(
    "Psychometric fit (%s): alpha = %.4f, beta = %.4f, ",
    "equal asymptote q = %.4f (random-lapse probability = %.4f); convergence = %d\n"
  ),
  sigmoid_name, fit_alpha, fit_beta, fit_q, 2 * fit_q,
