# create many hits and false alarms; very high thresholds create few of both.
# In multidimensional or non-Gaussian problems, the optimal acceptance region
# can be more complicated than one threshold.
thresholds <- seq(min(x), max(x), length.out = 1000)
tpr_theoretical <- 1 - pnorm(thresholds, loc_signal, sd_signal)
fpr_theoretical <- 1 - pnorm(thresholds, loc_noise, sd_noise)
p_correct_theoretical <- 0.5 * (tpr_theoretical + 1 - fpr_theoretical)

roc_fpr_theoretical <- c(1, fpr_theoretical, 0)
roc_tpr_theoretical <- c(1, tpr_theoretical, 0)
roc_auc <- auc_trapezoid(roc_fpr_theoretical, roc_tpr_theoretical)
cat(sprintf("Area under the theoretical ROC curve: %.4f\n", roc_auc))

