# Small helpers used throughout. Sorting inside auc_trapezoid makes it work
# whether an ROC was generated by increasing or decreasing thresholds.
auc_trapezoid <- function(x, y) {
  keep <- is.finite(x) & is.finite(y)
  x <- x[keep]
  y <- y[keep]
  ordering <- order(x)
  x <- x[ordering]
  y <- y[ordering]
  sum(diff(x) * (head(y, -1) + tail(y, -1)) / 2)
}

find_curve_crossing <- function(grid, difference, target = mean(range(grid))) {
  crossing_indices <- which(diff(sign(difference)) != 0)
  if (length(crossing_indices) == 0) {
    stop("No curve crossing was found on the supplied grid.")
  }
  crossings <- vapply(crossing_indices, function(index) {
    x1 <- grid[index]
    x2 <- grid[index + 1]
    y1 <- difference[index]
    y2 <- difference[index + 1]
    x1 - y1 * (x2 - x1) / (y2 - y1)
  }, numeric(1))
  crossings[which.min(abs(crossings - target))]
}

simulate_yes_count <- function(mean_response, n_trials, criterion, lapse) {
  internal_response <- rnorm(n_trials, mean_response, 1)
  respond_yes <- internal_response > criterion
  lapse_trials <- runif(n_trials) < lapse
  respond_yes[lapse_trials] <- runif(sum(lapse_trials)) < 0.5
  sum(respond_yes)
}

