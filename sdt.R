cat("Contrast | signal responses / trials\n")
for (i in seq_along(contrast_levels)) {
  cat(sprintf("%8.2f | %3d / %d\n", contrast_levels[i], yes_counts[i], n_per_level))
}

# -----------------------------------------------------------------------------
# 4. Fit a psychometric function
# -----------------------------------------------------------------------------
# R has several possible psychometric-fitting routes. stats::glm is excellent
# for ordinary logit/probit binomial models without fitted lapses. The psyphy
# package (sometimes described informally as "R psychophysics") supplies SDT
# utilities, psychophysical GLM links, and psyfun.2asym; quickpsy adds a convenient
# multi-group/bootstrap workflow; brms can express richer Bayesian models. To
# keep this file immediately runnable, the code below directly maximizes the
# grouped-binomial likelihood with base stats::optim. This also lets us impose
# the same lower/upper-asymptote constraint used in the Python and MATLAB files.
#
# Curve choices:
#   norm     additive Gaussian decision noise: Phi(beta * (x - alpha))
#   logistic logistic decision noise: plogis(beta * (x - alpha))
#   weibull  positive intensities: 1 - exp(-(x / alpha)^beta)
#
# The response probability is q + (1 - 2q) * core(x), where the lower and
# upper error asymptotes are constrained to the same q. Under random lapses,
# the corresponding total lapse probability is 2q.

sigmoid_name <- "norm"  # Change to "logistic" or "weibull".

predict_psychometric <- function(theta, stimulus, sigmoid) {
  # q is constrained to (0, 0.1), slope/scale parameters stay positive.
  q <- 0.1 * plogis(theta[3])
  if (sigmoid == "weibull") {
    alpha <- exp(theta[1])
    beta <- exp(theta[2])
    core <- 1 - exp(-(pmax(stimulus, 0) / alpha)^beta)
  } else {
    alpha <- theta[1]
    beta <- exp(theta[2])
    linear_predictor <- beta * (stimulus - alpha)
    core <- if (sigmoid == "norm") pnorm(linear_predictor) else
      plogis(linear_predictor)
  }
  q + (1 - 2 * q) * core
}

psychometric_nll <- function(theta, data, sigmoid) {
  probabilities <- predict_psychometric(theta, data$contrast, sigmoid)
  probabilities <- pmin(pmax(probabilities, 1e-12), 1 - 1e-12)
  -sum(dbinom(data$yes, data$trials, probabilities, log = TRUE))
}

if (sigmoid_name == "weibull") {
  theta_start <- c(log(median(contrast_levels)), log(2), qlogis(0.1))
} else {
  theta_start <- c(median(contrast_levels), log(0.25), qlogis(0.1))
}

psychometric_fit <- optim(
  theta_start,
  psychometric_nll,
  data = psychometric_data,
  sigmoid = sigmoid_name,
  method = "Nelder-Mead",
  control = list(maxit = 10000, reltol = 1e-10),
  hessian = TRUE
)

fit_theta <- psychometric_fit$par
fit_q <- 0.1 * plogis(fit_theta[3])
if (sigmoid_name == "weibull") {
  fit_alpha <- exp(fit_theta[1])
  fit_beta <- exp(fit_theta[2])
} else {
  fit_alpha <- fit_theta[1]
  fit_beta <- exp(fit_theta[2])
}

fit_grid <- seq(0, max(contrast_levels), length.out = 400)
fit_probability <- predict_psychometric(fit_theta, fit_grid, sigmoid_name)
plot(
  fit_grid, fit_probability, type = "l", lwd = 2,
  xlab = "Contrast (%)", ylab = "P('signal' response | signal trial)",
  ylim = c(0, 1), main = sprintf("Binomial ML fit: %s", sigmoid_name)
)
points(contrast_levels, yes_counts / n_per_level, pch = 19, col = "blue")
grid()

cat(sprintf(
  paste0(
    "Psychometric fit (%s): alpha = %.4f, beta = %.4f, ",
    "equal asymptote q = %.4f (random-lapse probability = %.4f); convergence = %d\n"
  ),
  sigmoid_name, fit_alpha, fit_beta, fit_q, 2 * fit_q,
  psychometric_fit$convergence
))
stopifnot(
  psychometric_fit$convergence == 0,
  is.finite(psychometric_fit$value),
  all(fit_probability > 0 & fit_probability < 1),
  fit_beta > 0,
  fit_q >= 0 && fit_q <= 0.1
)

# -----------------------------------------------------------------------------
# 5. From SDT to stimulus-dependent psychometric functions
# -----------------------------------------------------------------------------
# With unit variance and fixed criterion k:
#   H(x) = Phi(d'(x) - k), and F = Phi(-k).
# Thus H(x) depends jointly on the decision rule and the transducer mapping the
# physical stimulus to sensitivity. If d'(x) = gain*x, H(x) is cumulative
# Gaussian in x. A common nonlinear extension is d'(x) = (gain*x)^p.
#
# Fit signal and noise responses jointly when asking whether a manipulation
# changes gain, exponent, criterion, or lapse rate. If false-alarm rate or
# criterion changes with stimulus or condition, fitting hit rates alone
# confounds sensitivity and bias.

# The log-linear correction avoids infinite z-scores for observed rates 0 or 1.
hit_rate_corrected <- (yes_counts + 0.5) / (n_per_level + 1)
false_alarm_rate_corrected <- (false_alarm_count + 0.5) / (n_catch + 1)
empirical_dprime <- qnorm(hit_rate_corrected) - qnorm(false_alarm_rate_corrected)
stopifnot(
  all(is.finite(empirical_dprime)),
  length(empirical_dprime) == length(contrast_levels)
)

plot(
  contrast_levels, empirical_dprime, pch = 19,
  xlab = "Contrast (%)", ylab = "d'",
  main = "Stimulus-dependent sensitivity"
)
lines(contrast_levels, true_dprime, lwd = 2)
legend(
  "topleft", c("Estimated from H and F", sprintf("Generating d' = %.2f x", gain_true)),
  pch = c(19, NA), lty = c(NA, 1), lwd = c(NA, 2), bty = "n"
)
grid()

# -----------------------------------------------------------------------------
# Appendix A1. Estimating SDT measures from response counts
# -----------------------------------------------------------------------------
#                Respond "signal"  Respond "noise"
# Actual signal       Hit               Miss
# Actual noise        False alarm       Correct rejection
#
# H conditions on signal trials; F conditions on noise trials. Precision,
# hits/(hits + false alarms), instead conditions on the response and therefore
# changes with the signal base rate.

hits <- 40
misses <- 10
false_alarms <- 15
correct_rejections <- 135
hit_rate <- hits / (hits + misses)
false_alarm_rate_example <- false_alarms / (false_alarms + correct_rejections)
precision <- hits / (hits + false_alarms)
hit_rate_corrected_example <- (hits + 0.5) / (hits + misses + 1)
fa_rate_corrected_example <-
  (false_alarms + 0.5) / (false_alarms + correct_rejections + 1)
z_hit <- qnorm(hit_rate_corrected_example)
z_false_alarm <- qnorm(fa_rate_corrected_example)
dprime_observed <- z_hit - z_false_alarm
criterion_observed <- -0.5 * (z_hit + z_false_alarm)
stopifnot(
  is.finite(dprime_observed),
  is.finite(criterion_observed),
  dprime_observed > 0
)

cat(sprintf(
  "Hit rate: %.3f; false-alarm rate: %.3f\n",
  hit_rate, false_alarm_rate_example
))
cat(sprintf(
  "Corrected d': %.3f; corrected c: %.3f; precision: %.3f\n",
  dprime_observed, criterion_observed, precision
))

# Appendix A2. Unequal variance and alternative sensitivity indices
# If sigma_signal != sigma_noise, qnorm(H)-qnorm(F) varies with criterion.
# The zROC follows:
#   qnorm(H) = (mu_signal-mu_noise)/sigma_signal
#              + (sigma_noise/sigma_signal) * qnorm(F).
# Its slope is sigma_noise/sigma_signal, not 1. The log likelihood ratio is
# quadratic, so an optimal decision region can require two crossings. ROC/AUC
# and the general likelihood-ratio rule remain valid. A', d_a, and equal-
# variance d' have different interpretations and should be labelled clearly.

# -----------------------------------------------------------------------------
# Appendix A3. Two-interval, two-alternative forced choice
# -----------------------------------------------------------------------------
# Each trial contains one signal and one noise sample; choose the larger. Under
# independent draws from the same decision variable there is no criterion/caution
# term, although order and response biases may remain.

pdf_signal_minus_noise <- dnorm(
  diff_x, loc_signal - loc_noise, sqrt(sd_noise^2 + sd_signal^2)
)
pdf_noise_minus_signal <- dnorm(
  diff_x, loc_noise - loc_signal, sqrt(sd_noise^2 + sd_signal^2)
)
plot(
  diff_x, pdf_signal_minus_noise, type = "l", col = "blue", lwd = 2,
  xlab = "Difference", ylab = "Density",
  main = "Difference distributions in 2I-2AFC"
)
lines(diff_x, pdf_noise_minus_signal, col = "red", lwd = 2)
legend(
  "topright", c("Signal - noise", "Noise - signal"),
  col = c("blue", "red"), lty = 1, lwd = 2, bty = "n"
)
grid()

p_correct_2afc <- 1 - pnorm(
  0, loc_signal - loc_noise, sqrt(sd_noise^2 + sd_signal^2)
